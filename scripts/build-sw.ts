// After hash-assets: write dist/sw.js, the service worker that makes the site installable and work offline.
// Precache = the app shell (pages, entry JS/CSS, content, icons) + the files the first cabin view needs. Everything
// else is cached the first time it is used: content-hashed files cache-first (they never change), other files
// stale-while-revalidate, pages and JSON network-first with the cache as the offline fallback. Cross-origin
// requests (cartridges hosted elsewhere) are left to the browser.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const dist = join(import.meta.dir, '..', 'dist');
// the cabin page, and the sky-whale viewer (the one cartridge served from this origin: it plays offline too; its
// whale models are cached as they are first seen)
const html = ['index.html', 'whales/index.html'].map(f => readFileSync(join(dist, f), 'utf8')).join('\n');
// the hashed copy of a public/assets file (scripts/hash-assets.ts), falling back to the plain name
const hashed = (name: string) => {
  const slash = name.lastIndexOf('/'), dir = name.slice(0, slash + 1), file = name.slice(slash + 1);
  const dot = file.lastIndexOf('.'), base = file.slice(0, dot), ext = file.slice(dot);
  const hit = readdirSync(join(dist, 'assets', dir)).find(f => f.startsWith(`${base}.`) && f.endsWith(ext) && /^[0-9a-f]{8}$/.test(f.slice(base.length + 1, -ext.length)));
  return `/assets/${dir}${hit ?? file}`;
};
// entry scripts, styles and modulepreloads of the cabin page (Vite writes them as /assets/… in index.html)
const fromHtml = [...html.matchAll(/(?:src|href)="(\/assets\/[^"]+\.(?:js|css))"/g)].map(m => m[1]);
// …plus the chunks they import statically (three.js core etc.); dynamic import() chunks are cached on first use
for (let i = 0; i < fromHtml.length; i++) {
  if (!fromHtml[i].endsWith('.js')) continue;
  const js = readFileSync(join(dist, fromHtml[i]), 'utf8');
  for (const m of js.matchAll(/(?:from|import)\s*"\.\/([^"]+\.js)"/g))
    if (!fromHtml.includes(`/assets/${m[1]}`)) fromHtml.push(`/assets/${m[1]}`);
}
const shell = ['/', '/content.json', '/notes.json', '/manifest.webmanifest', '/favicon.svg',
  '/icons/icon-192.png', '/icons/icon-512.png', '/icons/apple-touch-icon.png', '/plain/', '/whales/', '/assets/whales/manifest.json'];
const firstView = ['fonts/fraunces-latin.woff2', 'fonts/fraunces-latin-ext.woff2', 'fonts/dmsans-latin.woff2', 'cabin.glb', 'collectibles.glb', 'captain.glb', 'sky.glb', 'sky_sunset.ktx2', 'lightmap_sunset_1k.ktx2', 'lightmaps.json'].map(hashed);
// the Basis transcoder that turns the KTX2 textures into the GPU's own compressed format (src/scene.ts initKTX2)
const basis = ['/basis/basis_transcoder.js', '/basis/basis_transcoder.wasm'];
const precache = [...new Set([...shell, ...fromHtml, ...firstView, ...basis])].filter(u => existsSync(join(dist, u === '/' || u.endsWith('/') ? `${u}index.html` : u)));

// a new worker whenever a precached file or this script (the worker's logic) changes
const version = createHash('sha256').update(readFileSync(import.meta.path)).update(precache.map(u => {
  const f = join(dist, u.endsWith('/') ? `${u}index.html` : u);
  return u + createHash('sha256').update(readFileSync(f)).digest('hex');
}).join('\n')).digest('hex').slice(0, 10);

const sw = `// generated by scripts/build-sw.ts — do not edit
const VERSION = ${JSON.stringify(version)};
const SHELL = 'kk-shell-' + VERSION, RUNTIME = 'kk-runtime', ASSETS = 'kk-assets';
const PRECACHE = ${JSON.stringify(precache)};
const HASHED = /\\/assets\\/.+[.-][0-9A-Za-z_-]{8}\\.[a-z0-9]+$/;
const MAX_ASSETS = 160;

self.addEventListener('install', e => {
  e.waitUntil(caches.open(SHELL).then(c => c.addAll(PRECACHE.map(u => new Request(u, { cache: 'reload' })))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) if (k.startsWith('kk-shell-') && k !== SHELL) await caches.delete(k);
    if (self.registration.navigationPreload) await self.registration.navigationPreload.enable().catch(() => {});
    await self.clients.claim();
  })());
});

const put = async (cache, req, res) => { if (res && (res.ok || res.type === 'opaque')) await (await caches.open(cache)).put(req, res.clone()); return res; };
const trim = async () => { const c = await caches.open(ASSETS), ks = await c.keys(); for (let i = 0; i < ks.length - MAX_ASSETS; i++) await c.delete(ks[i]); };
const fromCache = req => caches.match(req, { ignoreSearch: req.mode === 'navigate', ignoreVary: true });

async function networkFirst(e, cache) {
  const req = e.request;
  try {
    const res = (await e.preloadResponse) || await fetch(req);
    if (res.ok) e.waitUntil(put(cache, req, res.clone()));
    return res;
  } catch (err) {
    const hit = await fromCache(req);
    if (hit) return hit;
    if (req.mode === 'navigate') {
      const path = new URL(req.url).pathname;
      return (await caches.match(path.startsWith('/writing') || path.startsWith('/plain') ? '/plain/' : '/', { ignoreVary: true })) || Response.error();
    }
    throw err;
  }
}
async function cacheFirst(e, cache) {
  const hit = await caches.match(e.request, { ignoreVary: true });
  if (hit) return hit;
  const res = await fetch(e.request);
  e.waitUntil(put(cache, e.request, res.clone()).then(() => cache === ASSETS && trim()));
  return res;
}
async function staleWhileRevalidate(e, cache) {
  const hit = await caches.match(e.request, { ignoreVary: true });
  const net = fetch(e.request).then(res => put(cache, e.request, res.clone()).then(() => res));
  if (hit) { e.waitUntil(net.catch(() => {})); return hit; }
  return net;
}

self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET' || req.headers.has('range')) return;
  const url = new URL(req.url);
  if (url.origin === location.origin) {
    if (url.pathname === '/sw.js' || url.searchParams.has('nosw')) return;
    if (req.mode === 'navigate') return e.respondWith(networkFirst(e, RUNTIME));
    if (HASHED.test(url.pathname)) return e.respondWith(cacheFirst(e, ASSETS));
    if (url.pathname.endsWith('.json') || url.pathname.endsWith('.webmanifest')) return e.respondWith(networkFirst(e, RUNTIME));
    return e.respondWith(staleWhileRevalidate(e, RUNTIME));
  }
});
`;
writeFileSync(join(dist, 'sw.js'), sw);
console.log(`build-sw: sw.js v${version}, ${precache.length} files precached`);
